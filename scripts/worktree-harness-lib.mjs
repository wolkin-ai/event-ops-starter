import path from 'node:path';

export const DEFAULT_APP_PORT = 3001;
export const DEFAULT_STORYBOOK_PORT = 6007;
export const DEFAULT_HOST = '127.0.0.1';

export function validateWorktreeName(name) {
  if (!/^[a-z0-9][a-z0-9-]{1,62}$/.test(name)) {
    throw new Error(
      'Worktree name must use lowercase letters, numbers, or hyphens.',
    );
  }

  return name;
}

export function defaultBranchName(name) {
  return `codex/${validateWorktreeName(name)}`;
}

export function defaultWorktreePath(canonicalRoot, name) {
  return path.resolve(
    path.dirname(canonicalRoot),
    `${path.basename(canonicalRoot)}-${validateWorktreeName(name)}`,
  );
}

export function validateHost(host) {
  if (typeof host !== 'string' || host.trim() === '') {
    throw new Error('host must be a non-empty string.');
  }

  return host;
}

export function allocateWorktreeRuntime(existingRecords, overrides = {}) {
  const usedAppPorts = new Set(
    existingRecords.map((record) => record.appPort).filter(Number.isInteger),
  );
  const usedStorybookPorts = new Set(
    existingRecords
      .map((record) => record.storybookPort)
      .filter(Number.isInteger),
  );

  const appPort =
    overrides.appPort ?? firstAvailableNumber(usedAppPorts, DEFAULT_APP_PORT);
  const storybookPort =
    overrides.storybookPort ??
    firstAvailableNumber(usedStorybookPorts, DEFAULT_STORYBOOK_PORT);

  return {
    host: validateHost(overrides.host ?? DEFAULT_HOST),
    appPort,
    storybookPort,
  };
}

function firstAvailableNumber(usedNumbers, startingFrom) {
  let candidate = startingFrom;

  while (usedNumbers.has(candidate)) {
    candidate += 1;
  }

  return candidate;
}

export function createInitialRecord({
  name,
  branch,
  worktreePath,
  host,
  appPort,
  storybookPort,
  envSource,
}) {
  return {
    name,
    branch,
    path: worktreePath,
    host,
    appPort,
    storybookPort,
    envSource,
    createdAt: new Date().toISOString(),
    processes: {
      app: null,
      storybook: null,
    },
  };
}

export function renderEnvFile(baseContent, record) {
  const normalizedBase = baseContent.trimEnd();
  const observabilityDir = record.observabilityDir ?? '';
  const traceFile = record.traceFile ?? '';
  const metricsFile = record.metricsFile ?? '';

  return `${normalizedBase}

# Generated by ./bin/worktree-harness
WORKTREE_NAME="${record.name}"
WORKTREE_HOST="${record.host}"
WORKTREE_APP_PORT="${String(record.appPort)}"
WORKTREE_STORYBOOK_PORT="${String(record.storybookPort)}"
WORKTREE_OBSERVABILITY_DIR="${observabilityDir}"
WORKTREE_TRACE_FILE="${traceFile}"
WORKTREE_METRICS_FILE="${metricsFile}"
`;
}

export function parseWorktreeListPorcelain(output) {
  const entries = [];
  let current = null;

  for (const line of output.split('\n')) {
    if (line === '') {
      if (current !== null) {
        entries.push(current);
        current = null;
      }

      continue;
    }

    const [key, ...rest] = line.split(' ');
    const value = rest.join(' ');

    if (key === 'worktree') {
      if (current !== null) {
        entries.push(current);
      }

      current = {
        path: value,
      };
      continue;
    }

    if (current === null) {
      continue;
    }

    if (key === 'branch') {
      current.branch = value.replace(/^refs\/heads\//, '');
      continue;
    }

    if (key === 'HEAD') {
      current.head = value;
      continue;
    }

    if (key === 'detached') {
      current.detached = true;
    }
  }

  if (current !== null) {
    entries.push(current);
  }

  return entries;
}

export function toDisplayRecord(record, options = {}) {
  const appStatus = options.appRunning === true ? 'running' : 'stopped';
  const storybookStatus =
    options.storybookRunning === true ? 'running' : 'stopped';

  return [
    `${record.name}`,
    `  branch: ${record.branch}`,
    `  path: ${record.path}`,
    `  app: ${record.host}:${String(record.appPort)} (${appStatus})`,
    `  storybook: ${record.host}:${String(record.storybookPort)} (${storybookStatus})`,
  ].join('\n');
}
